param(
    [Parameter(Mandatory=$true)][string]$Build,
    [Parameter(Mandatory=$true)][string]$Package,
    [Parameter(Mandatory=$true)][string]$Output,
    [string]$Prefix = '',
    [int]$Rounds = 3
)

# Run in the container's MSVC developer environment. The packaged CMake bridge
# retains its compile-command tokenization; only the explicit prefix is added.
$ErrorActionPreference = 'Continue'
$ProgressPreference = 'SilentlyContinue'
$Build = (Resolve-Path $Build).Path.Replace('\', '/')
$Package = (Resolve-Path $Package).Path.Replace('\', '/')
New-Item -ItemType Directory -Force $Output | Out-Null
$Output = (Resolve-Path $Output).Path.Replace('\', '/')
if (-not $Prefix) {
    $Prefix = "$Build/CMakeFiles/pch_research.test.dir/cmake_pch.hxx"
}
$Prefix = (Resolve-Path $Prefix).Path.Replace('\', '/')
$resources = @(Get-ChildItem "$Package/share/omnirefl/clang" -Directory)
if ($resources.Count -ne 1) { throw 'Expected one Clang resource directory' }
$resource = $resources[0].FullName.Replace('\', '/')
$commands = Get-Content "$Build/compile_commands.json" -Raw | ConvertFrom-Json
$entries = @($commands | Where-Object {
    $_.file -match '\.cpp$' -and
    $_.command -match '[/\\]pch_research\.test\.dir[/\\]'
})
if ($entries.Count -eq 0) { throw 'No pch_research.test compilation commands' }

$bridge = Get-Content "$Package/lib/cmake/omnirefl/run_omnirefl_from_ccdb.cmake" -Raw
$addition = @'
if(DEFINED RESEARCH_PREFIX)
    list(APPEND _omnirefl_args --pch-header "${RESEARCH_PREFIX}"
        --pch-cache-dir "${RESEARCH_CACHE}")
endif()
'@
$bridge.Replace('list(APPEND _omnirefl_args -- ${_compiler_args})',
    "$addition`nlist(APPEND _omnirefl_args -- `${_compiler_args})") |
    Set-Content "$Output/bridge.cmake"

$records = @()
$reference = @{}
for ($round = 0; $round -lt $Rounds; ++$round) {
    $modes = if ($round % 2 -eq 0) { @('baseline', 'pch') }
        else { @('pch', 'baseline') }
    foreach ($mode in $modes) {
        Remove-Item "$Output/cache" -Recurse -Force -ErrorAction SilentlyContinue
        foreach ($entry in $entries) {
            $name = [IO.Path]::GetFileName($entry.file)
            $header = "$Output/$name.omnirefl.hpp"
            $arguments = @("-DCCDB_QUERY=$Package/bin/ccdb_query.exe",
                "-DOMNIREFL=$Package/bin/omnirefl.exe",
                "-DCOMP_DB=$Build/compile_commands.json",
                "-DSOURCE=$($entry.file)",
                '-DOUTPUT_CONTAINS=/pch_research.test.dir/',
                "-DOUT=$header", "-DRESOURCE_DIR=$resource", '-DTIMINGS=1')
            if ($mode -eq 'pch') {
                $arguments += @("-DRESEARCH_PREFIX=$Prefix",
                    "-DRESEARCH_CACHE=$Output/cache")
            }
            $arguments += @('-P', "$Output/bridge.cmake")
            $watch = [Diagnostics.Stopwatch]::StartNew()
            $text = & cmake @arguments 2>&1
            $code = $LASTEXITCODE
            $watch.Stop()
            $text | Out-File "$Output/$round-$mode-$name.log"
            if ($code -ne 0) { $text; exit $code }
            $content = @(Get-Content $header | Where-Object {
                $_ -and -not $_.StartsWith(
                    '// This file was generated by the omnirefl tool on ')
            } | Sort-Object)
            if (-not $reference.ContainsKey($name)) { $reference[$name] = $content }
            if (Compare-Object $reference[$name] $content) {
                throw "Reflection contents changed for $name"
            }
            $phases = @{}
            foreach ($match in [regex]::Matches(($text -join "`n"),
                '(?m)^([^:\n]+): .*\(([0-9]+) microseconds\)$')) {
                $phases[$match.Groups[1].Value] =
                    [double]$match.Groups[2].Value / 1e6
            }
            $record = [pscustomobject]@{
                round = $round; mode = $mode; file = $name
                wall = $watch.Elapsed.TotalSeconds; phases = $phases
                pch = @($text | Select-String 'instrumentation PCH:' |
                    ForEach-Object { $_.ToString() })
            }
            $records += $record
            $record | ConvertTo-Json -Compress
        }
        $records | ConvertTo-Json -Depth 5 |
            Set-Content "$Output/measurements.json" -Encoding UTF8
    }
}
