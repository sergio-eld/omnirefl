"""Unix timing harness: existing sources, distinct tool processes, cold prefixes."""
import argparse
import collections
import json
import os
import pathlib
import re
import shlex
import shutil
import statistics
import subprocess
import time

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--build', type=pathlib.Path, required=True)
parser.add_argument('--package', type=pathlib.Path, required=True)
parser.add_argument('--output', type=pathlib.Path, required=True)
parser.add_argument('--prefix', type=pathlib.Path)
parser.add_argument('--rounds', type=int, default=3)
parser.add_argument('--cpu', type=int)
args = parser.parse_args()
if hasattr(os, 'sched_setaffinity'):
    os.sched_setaffinity(0, {args.cpu if args.cpu is not None
                           else min(os.sched_getaffinity(0))})

build = args.build.resolve()
package = args.package.resolve()
output = args.output.resolve()
output.mkdir(parents=True, exist_ok=True)
resources = list((package / 'share/omnirefl/clang').glob('*/include'))
if len(resources) != 1:
    parser.error('Package must contain exactly one Clang resource directory')
entries = [entry for entry in json.loads((build / 'compile_commands.json').read_text())
           if pathlib.Path(entry['file']).suffix == '.cpp'
           and '/pch_research.test.dir/' in entry['command'].replace('\\', '/')]
if not entries:
    parser.error('No pch_research.test compilation commands found')
prefix = (args.prefix.resolve() if args.prefix else
          build / 'CMakeFiles/pch_research.test.dir/cmake_pch.hxx')
if not prefix.is_file():
    parser.error('Supply --prefix when the consumer does not enable CMake PCH')

reference = {}
records = []
for repeat in range(args.rounds):
    modes = ['baseline', 'pch'] if repeat % 2 == 0 else ['pch', 'baseline']
    for mode in modes:
        cache = output / 'cache'
        shutil.rmtree(cache, ignore_errors=True)
        for entry in entries:
            name = pathlib.Path(entry['file']).name
            header = output / (name + '.omnirefl.hpp')
            command = [str(package / 'bin/omnirefl'), '-c', entry['file'],
                       '-o', str(header), '--resource-dir', str(resources[0].parent),
                       '--timings']
            if mode == 'pch':
                command += ['--pch-header', str(prefix), '--pch-cache-dir', str(cache)]
            command += ['--', *shlex.split(entry['command'])]
            rss = output / 'peak-rss.txt'
            if pathlib.Path('/usr/bin/time').exists():
                command = ['/usr/bin/time', '-f', '%M', '-o', str(rss), *command]
            started = time.monotonic()
            run = subprocess.run(command, cwd=entry['directory'], text=True,
                                 stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            elapsed = time.monotonic() - started
            (output / f'{repeat}-{mode}-{name}.log').write_text(run.stdout)
            run.check_returncode()
            # Declaration order can change with PCH deserialization. Runtime
            # tests remain necessary; this comparison catches lost/added text.
            content = collections.Counter(line for line in header.read_text().splitlines()
                if line and not line.startswith(
                    '// This file was generated by the omnirefl tool on '))
            if name not in reference:
                reference[name] = content
            if content != reference[name]:
                raise RuntimeError(f'Reflection contents changed for {name}')
            phases = {match[1]: int(match[2]) / 1e6 for match in re.finditer(
                r'^([^:\n]+): .*\(([0-9]+) microseconds\)$', run.stdout, re.M)}
            row = dict(round=repeat, mode=mode, file=name, wall=elapsed,
                       peak_rss_kib=int(rss.read_text()) if rss.exists() else None,
                       phases=phases,
                       pch=[line for line in run.stdout.splitlines()
                            if 'instrumentation PCH:' in line])
            records.append(row)
            print(json.dumps(row), flush=True)
        (output / 'measurements.json').write_text(json.dumps(records, indent=2))

for mode in ('baseline', 'pch'):
    totals = [sum(row['wall'] for row in records
                  if row['round'] == repeat and row['mode'] == mode)
              for repeat in range(args.rounds)]
    print(f'{mode}: median full sequence = {statistics.median(totals):.3f}s')
